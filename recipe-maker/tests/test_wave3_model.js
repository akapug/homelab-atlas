'use strict';
const assert = require('assert');
const FM = require('../src/model.js');
const ADV = require('../src/advisor.js');
const D = require('../data.json');
const recipe = { box: 'odie', model: 'fnx', engine: 'strata', role: 'tool-calling', store: { types: ['gsq_iq3xxs'] } };
assert.equal(FM.earfCheck(D, recipe).status, 'FAIL');
assert.equal(FM.earfCheck(D, recipe, {minEarf: null}).status, 'FAIL');
for (const earf of [NaN, Infinity, -1, 1.1, '0.99'])
  assert.equal(FM.earfCheck(D, {...recipe, earf}).status, 'FAIL');
assert.equal(FM.earfCheck(D, {...recipe, earf: .98}).status, 'PASS');
const unknown = {...recipe, model: 'glm', store: {types: ['q8_0']}};
assert.equal(FM.earfCheck(D, unknown).status, 'UNKNOWN');
const partialData = {checks:{earf:{entries:{known:.99}}}};
const partialRecipe = {model:'fixture',engine:'fixture',role:'coding',store:{types:['known','unmeasured']}};
assert.equal(FM.earfCheck(partialData, partialRecipe).status, 'UNKNOWN');
assert.equal(FM.earfCheck(partialData, {...partialRecipe,earf:.99}).status, 'PASS');
const run = {id: 'unknown', recipe: unknown, measured: {kl_verdict:'PASS'}};
assert.equal(ADV.runQuality(D, run, [run]).status, 'UNKNOWN');
const local = {model: 'Qwen3.8-27B', engine: 'vllm-xpu', role:'coding', ctx: 24000, startup_tokens: 8001};
assert(FM.seatSafetyChecks(D, local).some(c => c.id === 'context_recall'));
assert(FM.seatSafetyChecks(D, local).some(c => c.id === 'startup_context' && c.status === 'FAIL'));
assert(FM.seatSafetyChecks(D, {...local, ctx: 12000, startup_tokens: 8000}).every(c => c.status === 'PASS'));
const batch = {model:'fnx', agents:33, serving:{batch:32}};
assert.equal(FM.seatSafetyChecks(D, batch)[0].status, 'FAIL');
assert.equal(FM.seatSafetyChecks(D, {...batch, admission:{policy:'engine'}})[0].status, 'FAIL');
assert.equal(FM.seatSafetyChecks(D, {...batch, admission:{policy:'door', conversations:32}})[0].status, 'PASS');
const original = FM.cardCurveFit(D);
D.multibox.card_curves.anchors.reverse();
const reordered = FM.cardCurveFit(D);
assert.deepStrictEqual(original.consts, reordered.consts);
assert(original.converged);
assert(original.solved.filter(x => x.status === 'SOLVED').every(x => Math.abs(x.residual) < 1e-5));
assert(!FM.seatSafetyChecks(D, {...local, model:'Qwen3.8-35B'}).some(x => x.id === 'context_recall'));
console.log('Wave 3 agent fidelity and admission checks passed');
